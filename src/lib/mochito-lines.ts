// ── Elegir qué dice ─────────────────────────────────────────────────

export interface SayContext {
  now: number;
  birthday?: string; // "MM-DD"
  did?: DidKind[]; // lo que hiciste hoy
}

const pad = (n: number) => String(n).padStart(2, "0");
const pickIn = <T,>(a: T[], p: number) => a[Math.min(a.length - 1, Math.floor(p * a.length))];

/** Frases de la fecha: cumpleaños o un día festivo. */
export function dateLines(now: number, birthday?: string): string[] {
  const d = new Date(now);
  const md = `${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  if (birthday && birthday === md) return BIRTHDAY;
  return HOLIDAYS.find((h) => h.md.includes(md))?.lines ?? [];
}

/** Frases del día de la semana, la quincena, el fin de mes y la temporada. */
export function calendarLines(now: number): string[] {
  const d = new Date(now);
  const out = [...WEEKDAY[d.getDay()]];
  const last = new Date(d.getFullYear(), d.getMonth() + 1, 0).getDate();
  if (d.getDate() === 15 || d.getDate() === last) out.push(...QUINCENA);
  if (d.getDate() >= last - 1) out.push(...MONTH_END);
  const m = d.getMonth() + 1;
  if (m >= 5 && m <= 10) out.push(...RAINY);
  if (m === 3 || m === 4) out.push(...HOT);
  return out;
}

/** Frases de lo que hiciste hoy (o de que todavía no hay nada). */
export function didLines(did: DidKind[] | undefined): string[] {
  if (!did) return [];
  if (!did.length) return DID.nothing;
  return did.flatMap((k) => DID[k]);
}

/**
 * Lo extra que puede decir: primero la fecha especial, luego lo que hiciste hoy,
 * y si no, de la semana, un chiste o ánimo. `pick` (0 a 1) decide.
 */
export function extraLine(ctx: SayContext, pick: number): string {
  const special = dateLines(ctx.now, ctx.birthday);
  if (special.length && pick < 0.4) return pickIn(special, pick / 0.4);
  const did = didLines(ctx.did);
  const cut = ctx.did?.length ? 0.6 : 0.2;
  if (did.length && pick < cut) return pickIn(did, pick / cut);
  const pool = [...calendarLines(ctx.now), ...JOKES, ...CHEER];
  return pickIn(pool, pick);
}

